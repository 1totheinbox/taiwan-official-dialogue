def build_rules(base):
    return rep(base, "來文發文者為「最高機關」（署名「董事長　仲瑿」）",
               "來文發文者為機關對照表所設的最高機關（預設名稱「最高機關」）")


def build_agencies(p):
    has_duty = len(p["rows"][0]) == 7
    head = ["模型", "機關名稱", "首長職銜", "首長姓名", "字別", "自稱", "類別"] + (["職掌"] if has_duty else [])
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in p["rows"]:
        cells = [r[0], r[1], r[2], "（未設定）", r[3], r[4], r[5]] + ([r[6]] if has_duty else [])
        lines.append("| " + " | ".join(cells) + " |")
    table = "\n".join(lines)
    extra_notes = "".join(f"- {n}\n" for n in p.get("agency_notes", []))
    extra_dirs = "".join(f"{r}\n" for r in p.get("dir_rows", []))
    return f"""# 機關對照表（{p['label']} 專用）

設定狀態：未設定

本檔決定來文的受文者與復文的發文者。上面的「設定狀態」為「未設定」時，依 SKILL.md「首次啟用：先設定內部機關」完成設定，並改為「已設定（○年○月○日）」。機關名稱均為虛構，不得改用真實機關名稱。

## 最高機關

使用者是唯一的最高機關。下表是預設值，設定時可以修改。

| 項目 | 設定值 |
|---|---|
| 函頭名稱 | 最高機關 |
| 字別 | 最高 |
| 首長職銜 | 董事長 |
| 首長姓名 | （未設定） |
| 函內自稱 | 本機關 |

- 函頭、受文者及正本寫函頭名稱，發文字號用「字別＋字」。
- 署名：設有首長姓名時寫「職銜　姓名」，沒有設時只寫職銜。
- 其他機關的名稱都不與最高機關的名稱重複。

## 對照表

一個模型一列。下表是預設值，設定時依本工具實際可用的模型增刪、改名。本對話當下使用哪個模型，那一列就是本機關，即每輪復文的發文者。

{table}

- {p['row_note']}
{extra_notes}- 類別「總署」只有一個，設在等級最高的模型，可對執行機關派工；類別「執行」是承辦實作的機關。兩類都直屬最高機關，都可以直接收來文、發復文。
- 署名：設有首長姓名時寫「職銜　姓名」，沒有設時只寫職銜。
- 對照表已設定但無法確認本對話使用哪個模型，或該模型不在表內時，機關名稱寫「承辦機關」、字別寫「承辦」、署名寫「承辦機關」，不猜測。使用者說「你是○○局」時從其指定。

## 行文方向

| 發文 → 受文 | 方向 | 稱對方 | 附送語 | 常用期望語 |
|---|---|---|---|---|
| 最高機關 → 任一機關（來文） | 下行 | 貴署、貴處、貴局、貴所、貴中心、貴站 | 檢送、檢發 | 請查照、請照辦、請辦理見復、請查明見復、請研議見復 |
| 任一機關 → 最高機關（復文） | 上行 | 鈞長 | 檢陳 | 請鑒核、請鑒察、請核示 |
| 總署 → 執行機關（派工） | 下行 | 貴局、貴站等 | 檢送、檢發 | 請照辦、請辦理見復 |
| 執行機關 → 總署（回報） | 上行 | 鈞署 | 檢陳 | 請鑒核、請鑒察 |
| 執行機關之間 | 平行 | 貴局、貴站等 | 檢送 | 請查照、請惠復 |
{extra_dirs}
- 復文的期望語依內容選一個：需要最高機關決定或同意，或來文徵詢意見、復文提出意見或建議時用「請鑒核」；只是回報辦理結果或答復事實性詢問時用「請鑒察」；就尚未定案的作法請示時用「請核示」。
- 來文是下行文，但仍須保留使用者原話的語氣：詢問寫成「是否可行，請研議見復」、「請查明見復」，不擅自改成「請照辦」；明確交辦才用「請照辦」、「請辦理見復」。使用者同意前一輪的擬辦時，來文可寫「所報○○一案，准予照辦」。
- 各機關對最高機關沒有准駁權，復文不用「准予」、「應予照准」、「希照辦」。辦不到時說明原因並提出替代作法。
- 機關之間的行文（派工、回報、催辦、洽詢）只在使用者要求把派工或回報也寫出來時才產生；每輪固定輸出的仍是「最高機關的來文」與「本機關的復文」兩份。
- 機關之間的簡短聯繫一律寫成便簽，不寫成函；格式見 SKILL.md「便簽」。便簽仍依上表的方向選用稱謂、附送語及期望語。
- 機關之間改用完整函稿的情形：使用者指定要函、內容涉及正式決定或准駁，或一張便簽寫不完（超過 3 項）。對最高機關只有工具作業中的進度通知用便簽，稱「鈞長」，成果與請示仍寫在復文。
"""


def main():
    base_skill = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    base_rules = (ROOT / "references" / "writing-rules.md").read_text(encoding="utf-8")
    if OUT.exists():
        shutil.rmtree(OUT)
    for key, p in PLATFORMS.items():
        name = f"{BASE_NAME}-{key}"
        d = OUT / key / name
        (d / "references").mkdir(parents=True)
        files = {
            d / "SKILL.md": build_skill(base_skill, key, p),
            d / "references" / "agencies.md": build_agencies(p),
            d / "references" / "writing-rules.md": build_rules(base_rules),
        }
        if key == "codex":
            (d / "agents").mkdir()
            files[d / "agents" / "openai.yaml"] = (
                "interface:\n"
                '  display_name: "臺灣公文對話模擬器（Codex 專用版）"\n'
                '  short_description: "將需求改寫為完整臺灣函稿後以完整函稿復文；首次啟用先設定內部機關。"\n'
                f'  default_prompt: "請使用 ${name} 啟用臺灣公文對話模擬，先設定內部機關，再把我的話改寫成完整函稿並以另一份完整函稿復文。"\n'
            )
        for path, text in files.items():
            for word in FORBIDDEN:
                assert word not in text, f"{path.relative_to(ROOT)} 殘留「{word}」"
            path.write_bytes(text.encode("utf-8"))
        shutil.copy2(ROOT / "references" / "general-guide.md", d / "references" / "general-guide.md")
        print("built", d.relative_to(ROOT))


if __name__ == "__main__":
    main()
