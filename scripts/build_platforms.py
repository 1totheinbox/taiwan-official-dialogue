# 產出檔不得殘留的字樣：原作者的人名、區名、跨平臺配置工具名稱
FORBIDDEN = ["仲瑿", "秦德", "硬耀", "西區", "東區", "南區", "西署長", "西局長", "西規", "paseo"]


def rep(text, old, new, count=1):
    n = text.count(old)
    assert n == count, f"預期 {count} 處，實得 {n} 處：{old[:40]}"
    return text.replace(old, new)


